export const LangContext = createContext({ lang: 'en', setLang: () => {} })

export function useI18n() {
  const { lang, setLang } = useContext(LangContext)
  const dict = MESSAGES[lang] || en
  const t = (key) => dict[key] ?? en[key] ?? key
  const tErr = (code) => (dict.errors?.[code]) ?? en.errors[code] ?? en.errors.generic
  const speechLang = LANGUAGES.find((l) => l.code === lang)?.speech || 'en-IN'
  return { lang, setLang, t, tErr, speechLang }
}
